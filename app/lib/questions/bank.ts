/** 單一題庫：所有題目的唯一來源。 */
export const QUESTION_BANK: Question[] = [...GENERAL_QUESTIONS, ...JOB_QUESTIONS];

/** 通用題（無 jobType／jobLevel）。 */
export function getGeneralQuestions(): Question[] {
  return QUESTION_BANK.filter((item) => !item.jobType && !item.jobLevel);
}

/** 指定職務 × 職級的題目；查無對應時回傳空陣列。 */
export function getJobQuestions(jobType: string, jobLevel: string): Question[] {
  return QUESTION_BANK.filter((item) => item.jobType === jobType && item.jobLevel === jobLevel);
}

/** 職務／職級未知時的預設行為題組。 */
export function getDefaultQuestionSet(): Question[] {
  return QUESTION_BANK.filter((item) => item.tags.includes('default-set'));
}

/** 模擬面試題組：有對應職務題就用職務題，否則用預設題組。 */
export function getInterviewQuestionSet(jobType: string, jobLevel: string): Question[] {
  const jobSet = getJobQuestions(jobType, jobLevel);
  return jobSet.length > 0 ? jobSet : getDefaultQuestionSet();
}

